out_tot = sum(out_pg.values())


def pct(x, k=1):
    return f"{100 * x:.{k}f}%"


def ci(v, k=1):
    return f"{100 * v[0]:.{k}f}–{100 * v[2]:.{k}f}%"


def ci_raw(v, k=2):
    return f"{v[0]:.{k}f}–{v[2]:.{k}f}"


cb = c["cluster_bootstrap"]
h4b = h4["block_bootstrap_5deg"]
rows = [
    ("P1a", "≥ 10% of vegetated land-months outside support", f"{pct(p['O1_area'])} ({ci(b['O1_area'])})",
     "met" if p["O1_area"] >= 0.10 else "not met"),
    ("P1b", "Arid > tropical", f"A {pct(p['O1_A'])} vs B {pct(p['O1_B'])}; B > A in "
     f"{pct(b['P_B_greater_than_A'], 0)} of bootstraps", "falsified" if p["O1_A"] > p["O1_B"] else "met"),
    ("P1c", "≥ 25% of outside points inside every marginal range",
     f"{pct(p['P1c_share_outside_but_inside_all_marginals'], 0)} ({ci(b['P1c'], 0)})",
     "met" if p["P1c_share_outside_but_inside_all_marginals"] >= 0.25 else "not met"),
    ("P2", "Held-out RMSE outside / inside ≥ 1.5 (falsifier < 1.1)",
     f"{c['P2_ratio_out_in']:.2f} ({ci_raw(cb['P2_ratio_out_in'])}); GBM {sg['gbm']['P2_ratio_out_in']:.2f}",
     "met" if c["P2_ratio_out_in"] >= 1.5 else ("falsified" if c["P2_ratio_out_in"] < 1.1 else
                                                 "not met, not falsified" + (" (interval spans 1.1)"
                                                                             if cb["P2_ratio_out_in"][0] < 1.1 else ""))),
    ("P2b", "Site partial Spearman(distance, RMSE | GPP) > 0",
     f"{c['P2b_site_partial_spearman_d_rmse_given_gpp']:.2f}",
     "met" if c["P2b_site_partial_spearman_d_rmse_given_gpp"] > 0 else "not met"),
    ("P3a", "Spearman(seed spread, |error|) < 0.3",
     f"{c['P3a_spearman_spread_abs_err']:.2f} ({ci_raw(cb['P3a_spearman_spread_abs_err'])})",
     "met" if c["P3a_spearman_spread_abs_err"] < 0.3 else "not met"),
    ("P3b", "RMSE / RMS spread > 2, larger outside support",
     f"{c['P3b_calibration_ratio_all']:.1f} ({ci_raw(cb['P3b_calibration_ratio_all'], 1)}); inside "
     f"{c['P3b_calibration_ratio_inside']:.1f} vs outside {c['P3b_calibration_ratio_outside']:.1f}",
     "first part met; second not met" if c["P3b_calibration_ratio_outside"] < c["P3b_calibration_ratio_inside"]
     else "met"),
    ("P4", "Spearman(GPP_std, distance) < 0.3 (falsifier ≥ 0.5)",
     f"{h4['P4_spearman_std_d']:.2f} ({ci_raw(h4b['P4'])})",
     "met" if h4["P4_spearman_std_d"] < 0.3 else ("falsified" if h4["P4_spearman_std_d"] >= 0.5
                                                  else "not met, not falsified")),
    ("P4b", "Same, partial given GPP, < 0.3",
     f"{h4['P4b_partial_spearman_std_d_given_gpp']:.2f} ({ci_raw(h4b['P4b'])})",
     "met" if h4["P4b_partial_spearman_std_d_given_gpp"] < 0.3 else "not met"),
    ("P4c", "Relative spread outside / inside < 1.5",
     f"{h4['P4c_ratio_median_cv_out_over_in']:.2f} ({ci_raw(h4b['P4c'])})",
     "met" if h4["P4c_ratio_median_cv_out_over_in"] < 1.5 else "not met"),
    ("P5", "More extrapolation in 2015–2022 than 2001–2014; trend > 0",
     f"{pct(sup['H5']['O1_mean_2015_2022'])} vs {pct(sup['H5']['O1_mean_2001_2014'])} "
     f"(Welch p = {sup['H5']['welch_p']:.2f}); {100*sup['H5']['trend_O1_per_decade']:+.1f} pts/decade",
     "met on paper; effect negligible"),
    ("H6", "Exploratory: per-site standardisation collapses support",
     f"{pct(sup['H6_per_entity']['O1_area'])} outside; surrogate RMSE {sg['persite']['RMSE']:.2f} vs {c['RMSE']:.2f}",
     "expectation half wrong"),
]
